import streamlit as st
import pandas as pd
import time
import os

# -----------------------------------------------------------------------------
# 0. Page Configuration
# -----------------------------------------------------------------------------
st.set_page_config(
    page_title="HK Cafe Selection Analysis System",
    page_icon="☕",
    layout="wide"
)

st.title("☕ Hong Kong Cafe Selection & District Rent Analysis System")
st.caption("Empowering F&B entrepreneurs to evaluate district potential, explore customer sentiment, and discover real-time commercial leasing opportunities.")

# -----------------------------------------------------------------------------
# 1. Real Rental Data & Mock District Data Definitions
# -----------------------------------------------------------------------------
@st.cache_data
def load_real_rental_data():
    """Load real rental data from CSV generated by scrape_28hse.py"""
    csv_path = "data/rent_listings_clean.csv"
    if os.path.exists(csv_path):
        try:
            df = pd.read_csv(csv_path)
            return df
        except Exception as e:
            st.error(f"Error loading CSV: {e}")
            return pd.DataFrame()
    return pd.DataFrame()

def get_mock_business_districts():
    """Get available business districts matching the scraper config"""
    return ["Sheung Wan", "Sai Ying Pun", "Causeway Bay", "Tsim Sha Tsui", "Sham Shui Po"]

def get_mock_district_summary(district_name):
    """Simulate core metrics and LLM review keywords for a district (to be replaced by member 3)"""
    summary = {
        "avg_spend": 78.5,           # Average spending per customer (HKD)
        "avg_sqft_rent": 115.0,      # Average rent per sq. ft. (HKD)
        "rent_pressure_index": 7.2,  # Rent Pressure Index (1-10)
        "total_cafes": 42
    }
    
    # Review keywords and representative quotes
    keywords_with_reviews = {
        "☕ Excellent Coffee Quality": [
            "Great variety of hand drip options, single-origin beans have distinct and surprising flavor profiles!",
            "Top-notch coffee quality and beautiful latte art, definitely worth returning."
        ],
        "📸 Instagrammable Interior": [
            "Industrial style interior is very photogenic with amazing natural lighting, long queues on weekends.",
            "Unique shop design with full cozy vibes."
        ],
        "💸 Higher Price Point": [
            "A Flat White costs $55, price-to-performance ratio is average.",
            "Portions are a bit small with slightly high unit prices."
        ],
        "🤫 Quiet Atmosphere": [
            "Not too crowded on weekdays, perfect for working with a laptop for an afternoon.",
            "Background music is played just right, not noisy at all."
        ]
    }
    return summary, keywords_with_reviews

# -----------------------------------------------------------------------------
# 2. Sidebar: Reordered Form Control Panel (English UI)
# -----------------------------------------------------------------------------
with st.sidebar:
    st.header("🎛️ Filter & Search Control Panel")
    
    # Form ensures right-hand page updates only after submitting search
    with st.form(key="search_form"):
        
        # --- Section 1: District Filter ---
        st.subheader("📍 1. District Selection")
        selected_district = st.selectbox(
            "Select Target District:",
            options=get_mock_business_districts()
        )

        st.divider()

        # --- Section 2: Rental Property Filters (1,000 - 100,000 HKD) ---
        st.subheader("🏪 2. Rental Property Filters")
        price_range = st.slider(
            "Monthly Rent Range (HKD):", 
            min_value=1000, 
            max_value=100000, 
            value=(10000, 60000), 
            step=1000
        )
        min_size = st.number_input("Minimum Area (sq.ft.):", min_value=50, max_value=2000, value=300, step=50)

        st.divider()

        # --- Section 3: Search Box & Button ---
        st.subheader("🔍 3. Keyword Search")
        search_keyword = st.text_input(
            "Enter keyword (street/building name):", 
            placeholder="e.g., Queen's Road..."
        )
        
        # Submit search button
        submit_search = st.form_submit_button("Search / Refresh Data", use_container_width=True)

# -----------------------------------------------------------------------------
# 3. Main Dashboard Layout & Dynamic Refresh Logic
# -----------------------------------------------------------------------------
summary, keywords_map = get_mock_district_summary(selected_district)
raw_rental_df = load_real_rental_data()

if submit_search:
    with st.spinner(f"Syncing latest district and leasing data for [{selected_district}]..."):
        time.sleep(1.0)
    st.success(f"Successfully loaded analysis results for [{selected_district}]!")

st.header(f"📍 Currently Analyzed District: {selected_district}")
if search_keyword:
    st.info(f"Active search keyword: **{search_keyword}**")

# --- Module 1: Core Economic & Business Metrics ---
st.subheader("📊 Core Business Metrics Overview")
col1, col2, col3, col4 = st.columns(4)

with col1:
    st.metric("Avg. Spend / Customer", f"HKD ${summary['avg_spend']}")
with col2:
    st.metric("Avg. Rent / Sq.Ft.", f"HKD ${summary['avg_sqft_rent']}")
with col3:
    st.metric("Rent Pressure Index", f"{summary['rent_pressure_index']} / 10", delta="Medium-High", delta_color="inverse")
with col4:
    st.metric("Specialty Cafes in District", f"{summary['total_cafes']} shops")

st.divider()

# --- Module 2: Customer Sentiment Keywords & Dialog Popups ---
st.subheader("💬 Customer Feedback Sentiment Analysis (Click tags to view reviews)")
st.write("Core consumer dimensions extracted via Large Language Model (LLM):")

kw_cols = st.columns(len(keywords_map))
for i, (kw, reviews) in enumerate(keywords_map.items()):
    with kw_cols[i % len(keywords_map)]:
        if st.button(f"🏷️ {kw}", key=f"kw_btn_{i}", use_container_width=True):
            @st.dialog(f"Customer Reviews for [{kw}]")
            def show_reviews_dialog():
                st.write("**🤖 LLM Summary:** Customer discussions are highly concentrated around this dimension.")
                st.divider()
                st.write("**📜 Representative Review Quotes:**")
                for r in reviews:
                    st.info(f"“ {r} ”")
            show_reviews_dialog()

st.divider()

# --- Module 3: Filterable Real Rental Listings Table with Clickable Links ---
st.subheader("🏢 Available Rental Properties in District (Powered by Scraper)")

if not raw_rental_df.empty and "district" in raw_rental_df.columns:
    # Filter by selected district
    district_df = raw_rental_df[raw_rental_df["district"] == selected_district]
    
    # Apply sidebar slider & number input filters
    filtered_df = district_df[
        (district_df["rent_monthly"] >= price_range[0]) &
        (district_df["rent_monthly"] <= price_range[1]) &
        (district_df["area_sqft_gross"] >= min_size)
    ]
    
    # Filter by search keyword if provided
    if search_keyword:
        filtered_df = filtered_df[
            filtered_df["title"].str.contains(search_keyword, case=False, na=False) |
            filtered_df["building"].str.contains(search_keyword, case=False, na=False)
        ]
    
    if not filtered_df.empty:
        # Select and rename columns for display
        display_df = filtered_df[[
            "title", "building", "area_sqft_gross", "rent_monthly", "rent_psf", "url"
        ]].copy()
        
        display_df.columns = [
            "Listing Title", "Building / Mall", "Area (sq.ft.)", 
            "Monthly Rent (HKD)", "Rent/sq.ft. (HKD)", "Listing Link"
        ]
        
        st.dataframe(
            display_df,
            use_container_width=True,
            hide_index=True,
            column_config={
                "Listing Link": st.column_config.LinkColumn(
                    "Property Listing URL",
                    display_text="🔗 View on 28Hse",
                    help="Click to open the live 28Hse property page"
                ),
                "Monthly Rent (HKD)": st.column_config.NumberColumn(
                    "Monthly Rent (HKD)",
                    format="HK$ %d"
                ),
                "Rent/sq.ft. (HKD)": st.column_config.NumberColumn(
                    "Rent/sq.ft. (HKD)",
                    format="HK$ %.1f"
                ),
                "Area (sq.ft.)": st.column_config.NumberColumn(
                    "Area (sq.ft.)",
                    format="%d sq.ft."
                )
            }
        )
        st.caption(f"Found {len(display_df)} matching rental properties in {selected_district}.")
    else:
        st.info(f"No rental properties found in [{selected_district}] matching your current price range or search keywords.")
else:
    st.warning("⚠️ Local rental CSV data not found or empty. Please run `python src/scrape_28hse.py` first to generate `data/rent_listings_clean.csv`.")